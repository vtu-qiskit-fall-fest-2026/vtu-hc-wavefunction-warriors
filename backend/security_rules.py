# Cache for the loaded knowledge base
_KB_CACHE: dict[str, Any] | None = None


def load_knowledge_base(kb_path: Path | str | None = None) -> dict[str, Any]:
    """
    Load the curated algorithm knowledge base from JSON.

    Args:
        kb_path: Optional path to the knowledge base JSON file. Defaults to
                 KNOWLEDGE_BASE_PATH relative to this file.

    Returns:
        Dictionary containing the parsed knowledge base.

    Raises:
        FileNotFoundError: If the knowledge base JSON file does not exist.
        json.JSONDecodeError: If the file is not valid JSON.
    """
    global _KB_CACHE
    target_path = Path(kb_path) if kb_path is not None else KNOWLEDGE_BASE_PATH

    if _KB_CACHE is not None and kb_path is None:
        return _KB_CACHE

    if not target_path.exists():
        raise FileNotFoundError(
            f"Knowledge base file not found at: {target_path}. "
            "Please ensure 'algorithms.json' exists in the module directory."
        )

    with target_path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    if kb_path is None:
        _KB_CACHE = data

    return data


def normalize_algorithm_name(
    raw_name: Any, kb: dict[str, Any] | None = None
) -> str | None:
    """
    Resolve a user-provided algorithm name to its canonical identifier in the knowledge base.

    Handles whitespace, casing, hyphens, and defined aliases.

    Args:
        raw_name: Input algorithm name.
        kb: Optional loaded knowledge base.

    Returns:
        Canonical algorithm name (e.g., 'RSA', 'ML-KEM') or None if not recognized.
    """
    if raw_name is None or not isinstance(raw_name, str):
        return None

    cleaned = raw_name.strip()
    if not cleaned:
        return None

    if kb is None:
        kb = load_knowledge_base()

    algorithms = kb.get("algorithms", {})

    # Direct match (case-insensitive)
    for canonical_name in algorithms:
        if cleaned.lower() == canonical_name.lower():
            return canonical_name

    # Alias match
    cleaned_normalized = cleaned.lower().replace(" ", "").replace("_", "").replace("-", "")
    for canonical_name, data in algorithms.items():
        aliases = data.get("aliases", [])
        for alias in aliases:
            alias_norm = alias.lower().replace(" ", "").replace("_", "").replace("-", "")
            if cleaned_normalized == alias_norm or cleaned.lower() == alias.lower():
                return canonical_name

    return None


def normalize_use_case(raw_use_case: Any, algorithm_hint: str | None = None) -> str | None:
    """
    Normalize user-provided cryptographic use case into a canonical category.

    Args:
        raw_use_case: Input use case string.
        algorithm_hint: Optional parameter preserved for interface compatibility.
                        Use cases are not inferred from algorithms to prevent ambiguous remapping.

    Returns:
        Canonical use case ('key_establishment', 'digital_signatures', 'symmetric_encryption')
        or None if unrecognized or ambiguous.
    """
    if raw_use_case is None or not isinstance(raw_use_case, str):
        return None

    cleaned = raw_use_case.strip().lower()
    if not cleaned:
        return None

    # Ambiguous use cases: "encryption" without qualification is rejected as ambiguous
    # rather than guessing between key establishment (transport) and symmetric encryption.
    if cleaned in ("encryption", "public_key_encryption", "asymmetric_encryption"):
        return None

    return USE_CASE_ALIASES.get(cleaned)


def get_supported_algorithms() -> list[str]:
    """Return a list of all canonical algorithm names supported by the security engine."""
    kb = load_knowledge_base()
    return list(kb.get("algorithms", {}).keys())


def get_supported_use_cases(algorithm: str | None = None) -> list[str]:
    """
    Return supported canonical use cases.

    If an algorithm is provided, returns use cases valid for that specific algorithm;
    otherwise returns all canonical use cases defined in the knowledge base.
    """
    kb = load_knowledge_base()
    if algorithm is None:
        return list(kb.get("use_cases", {}).keys())

    canonical_alg = normalize_algorithm_name(algorithm, kb)
    if not canonical_alg:
        return []

    return kb.get("algorithms", {}).get(canonical_alg, {}).get("supported_use_cases", [])


def _build_result(
    *,
    algorithm: str,
    use_case: str,
    risk_level: str,
    reason: str,
    recommendation: str,
    recommended_algorithms: list[str],
    priority: str,
    family: str,
    references: list[str],
    disclaimer: str = DEFAULT_DISCLAIMER,
) -> dict[str, Any]:
    """Helper to enforce consistent result format and types across all branches."""
    return {
        "algorithm": algorithm,
        "use_case": use_case,
        "risk_level": risk_level,
        "reason": reason,
        "recommendation": recommendation,
        "recommended_algorithms": recommended_algorithms,
        "priority": priority,
        "family": family,
        "references": references,
        "disclaimer": disclaimer,
    }


def _handle_unsupported_combination(
    canonical_alg: str,
    canonical_use_case: str,
    alg_data: dict[str, Any],
) -> dict[str, Any]:
    """Construct a cryptographically accurate assessment for unsupported algorithm/use-case pairs."""
    family = alg_data.get("family", "Unknown")
    supported_cases = alg_data.get("supported_use_cases", [])

    # Detailed contextual explanations
    if canonical_alg == "ML-KEM" and canonical_use_case == "digital_signatures":
        reason = (
            "ML-KEM is a Key-Encapsulation Mechanism (KEM) standardized under NIST FIPS 203 "
            "designed specifically for key establishment. It does not provide digital signatures "
            "or non-repudiation. For post-quantum digital signatures, select ML-DSA (FIPS 204) or "
            "SLH-DSA (FIPS 205)."
        )
        recommendation = (
            "Select an appropriate standardized post-quantum digital signature scheme: ML-DSA "
            "(FIPS 204) for general applications or SLH-DSA (FIPS 205) for state-free hash-based signing."
        )
        recommended = ["ML-DSA", "SLH-DSA"]
        refs = [
            "https://csrc.nist.gov/pubs/fips/203/final",
            "https://csrc.nist.gov/pubs/fips/204/final",
            "https://csrc.nist.gov/pubs/fips/205/final",
        ]

    elif canonical_alg in ("ML-DSA", "SLH-DSA") and canonical_use_case in ("key_establishment", "symmetric_encryption"):
        reason = (
            f"{canonical_alg} is a post-quantum digital signature scheme and cannot be used for "
            f"{canonical_use_case.replace('_', ' ')}. For post-quantum key establishment, select ML-KEM (FIPS 203)."
        )
        recommendation = (
            "For key establishment, deploy ML-KEM (FIPS 203). For symmetric bulk encryption, "
            "use AES-256."
        )
        recommended = ["ML-KEM"] if canonical_use_case == "key_establishment" else ["AES-256"]
        refs = [
            "https://csrc.nist.gov/pubs/fips/203/final",
            GENERAL_PQC_REFERENCE,
        ]

    elif canonical_alg == "ECDSA" and canonical_use_case in ("key_establishment", "symmetric_encryption"):
        reason = (
            "ECDSA is an elliptic curve digital signature scheme intended solely for authentication "
            "and integrity verification; it cannot establish shared secrets or perform data encryption. "
            "Classical key agreement uses ECDH, but both ECDSA and ECDH are vulnerable to Shor's algorithm."
        )
        recommendation = (
            "Use ML-KEM (FIPS 203) for post-quantum key establishment, or AES-256 for symmetric encryption."
        )
        recommended = ["ML-KEM"] if canonical_use_case == "key_establishment" else ["AES-256"]
        refs = ["https://csrc.nist.gov/pubs/fips/203/final", GENERAL_PQC_REFERENCE]

    elif canonical_alg == "ECDH" and canonical_use_case in ("digital_signatures", "symmetric_encryption"):
        reason = (
            "ECDH is an elliptic curve Diffie-Hellman key agreement protocol and cannot generate "
            "digital signatures or encrypt bulk data directly."
        )
        recommendation = (
            "For digital signatures, migrate to ML-DSA (FIPS 204) or SLH-DSA (FIPS 205). "
            "For bulk encryption, use AES-256."
        )
        recommended = ["ML-DSA", "SLH-DSA"] if canonical_use_case == "digital_signatures" else ["AES-256"]
        refs = [
            "https://csrc.nist.gov/pubs/fips/204/final",
            "https://csrc.nist.gov/pubs/fips/205/final",
        ]

    elif canonical_alg in ("AES-128", "AES-256") and canonical_use_case in ("key_establishment", "digital_signatures"):
        reason = (
            f"{canonical_alg} is a symmetric block cipher designed for data confidentiality. It does not "
            f"provide asymmetric {canonical_use_case.replace('_', ' ')} capabilities."
        )
        if canonical_use_case == "key_establishment":
            recommendation = "Use ML-KEM (FIPS 203) for post-quantum key establishment."
            recommended = ["ML-KEM"]
            refs = ["https://csrc.nist.gov/pubs/fips/203/final", GENERAL_PQC_REFERENCE]
        else:
            recommendation = "Use ML-DSA (FIPS 204) or SLH-DSA (FIPS 205) for post-quantum digital signatures."
            recommended = ["ML-DSA", "SLH-DSA"]
            refs = [
                "https://csrc.nist.gov/pubs/fips/204/final",
                "https://csrc.nist.gov/pubs/fips/205/final",
            ]

    elif canonical_alg == "RSA" and canonical_use_case == "symmetric_encryption":
        reason = (
            "RSA is an asymmetric (public-key) algorithm and is not designed or suitable for bulk symmetric "
            "data encryption due to payload constraints and performance overhead."
        )
        recommendation = (
            "Use AES-256 for symmetric bulk data encryption and protect key exchanges with ML-KEM (FIPS 203)."
        )
        recommended = ["AES-256"]
        refs = [GENERAL_PQC_REFERENCE]

    else:
        supported_str = ", ".join(supported_cases) if supported_cases else "none"
        reason = (
            f"Algorithm '{canonical_alg}' is not supported for use case '{canonical_use_case}'. "
            f"Supported use cases for {canonical_alg} are: {supported_str}."
        )
        recommendation = f"Select a compatible use case for {canonical_alg} ({supported_str})."
        recommended = []
        refs = [GENERAL_PQC_REFERENCE]

    return _build_result(
        algorithm=canonical_alg,
        use_case=canonical_use_case,
        risk_level="Unsupported Combination",
        reason=reason,
        recommendation=recommendation,
        recommended_algorithms=recommended,
        priority="N/A",
        family=family,
        references=refs,
    )


def assess_algorithm(algorithm: Any, use_case: Any) -> dict[str, Any]:
    """
    Perform a deterministic, rule-based cryptographic risk assessment for an algorithm and use case.

    Args:
        algorithm: Name or alias of the cryptographic algorithm (e.g., 'RSA', 'AES-256', 'ML-KEM').
        use_case: Intended cryptographic use case (e.g., 'key_establishment', 'digital_signatures',
                  'symmetric_encryption').

    Returns:
        A dictionary containing the assessment results with the following keys:
            - algorithm (str): Canonical or input algorithm name.
            - use_case (str): Canonical or input use case name.
            - risk_level (str): Qualitative prototype risk level.
            - reason (str): Cryptographic explanation of risk and quantum impact.
            - recommendation (str): Actionable next step or transition guidance.
            - recommended_algorithms (list[str]): Recommended standardized alternatives.
            - priority (str): Qualitative migration priority ('Immediate', 'High', 'Medium', 'Low', 'Maintain', 'N/A').
            - family (str): Cryptographic family classification.
            - references (list[str]): Authoritative references (NIST standards).
            - disclaimer (str): Educational prototype disclaimer notice.
    """
    # 1. Input validation for null, non-string, or empty values
    if algorithm is None or not isinstance(algorithm, str) or not algorithm.strip():
        display_alg = str(algorithm) if algorithm is not None else ""
        display_use_case = str(use_case) if use_case is not None else ""
        return _build_result(
            algorithm=display_alg,
            use_case=display_use_case,
            risk_level="Invalid Input",
            reason="Algorithm name must be a non-empty string.",
            recommendation="Please provide a valid cryptographic algorithm name (e.g., RSA, ECDH, ECDSA, AES-128, AES-256, ML-KEM, ML-DSA, SLH-DSA).",
            recommended_algorithms=[],
            priority="N/A",
            family="Unknown",
            references=[GENERAL_PQC_REFERENCE],
        )

    if use_case is None or not isinstance(use_case, str) or not use_case.strip():
        display_alg = algorithm.strip()
        display_use_case = str(use_case) if use_case is not None else ""
        return _build_result(
            algorithm=display_alg,
            use_case=display_use_case,
            risk_level="Invalid Input",
            reason="Use case must be a non-empty string.",
            recommendation="Please specify a valid cryptographic use case (e.g., key_establishment, digital_signatures, symmetric_encryption).",
            recommended_algorithms=[],
            priority="N/A",
            family="Unknown",
            references=[GENERAL_PQC_REFERENCE],
        )

    raw_alg_str = algorithm.strip()
    raw_use_case_str = use_case.strip()

    # 2. Load knowledge base
    try:
        kb = load_knowledge_base()
    except Exception as exc:
        return _build_result(
            algorithm=raw_alg_str,
            use_case=raw_use_case_str,
            risk_level="Error",
            reason=f"Failed to load cryptographic knowledge base: {exc}",
            recommendation="Ensure 'algorithms.json' is present in the application directory and contains valid JSON.",
            recommended_algorithms=[],
            priority="N/A",
            family="Unknown",
            references=[GENERAL_PQC_REFERENCE],
        )

    # 3. Canonicalize algorithm name
    canonical_alg = normalize_algorithm_name(raw_alg_str, kb)
    if canonical_alg is None:
        supported_list = ", ".join(kb.get("algorithms", {}).keys())
        alg_lower = raw_alg_str.lower().replace("-", "").replace("_", "")

        distinct_scheme_explanations = {
            "x25519": (
                f"Algorithm '{raw_alg_str}' is a Montgomery curve Diffie-Hellman function (RFC 7748). "
                "While related to elliptic-curve cryptography, it is a distinct scheme from standard NIST ECDH "
                f"and is not indexed as an alias. Currently supported algorithms: {supported_list}."
            ),
            "ed25519": (
                f"Algorithm '{raw_alg_str}' is an Edwards-curve Digital Signature Algorithm (EdDSA / RFC 8032). "
                "It is a distinct signature scheme from ECDSA and is not indexed as an alias. "
                f"Currently supported algorithms: {supported_list}."
            ),
            "ed448": (
                f"Algorithm '{raw_alg_str}' is an Edwards-curve Digital Signature Algorithm (EdDSA / RFC 8032). "
                "It is a distinct signature scheme from ECDSA and is not indexed as an alias. "
                f"Currently supported algorithms: {supported_list}."
            ),
            "eddsa": (
                f"Algorithm '{raw_alg_str}' is an Edwards-curve Digital Signature Algorithm family (RFC 8032). "
                "It is distinct from ECDSA and is not indexed as an alias. "
                f"Currently supported algorithms: {supported_list}."
            ),
        }

        if alg_lower in distinct_scheme_explanations:
            reason = distinct_scheme_explanations[alg_lower]
            recommendation = (
                f"Please specify a currently supported algorithm ({supported_list}). "
                "For post-quantum migration, transition directly to NIST standardized PQC algorithms (ML-KEM, ML-DSA, SLH-DSA)."
            )
        else:
            reason = (
                f"Algorithm '{raw_alg_str}' is not indexed in the curated knowledge base. "
                f"Currently supported algorithms: {supported_list}."
            )
            recommendation = "Verify spelling or select an indexed algorithm from the supported list."

        return _build_result(
            algorithm=raw_alg_str,
            use_case=raw_use_case_str,
            risk_level="Unrecognized Algorithm",
            reason=reason,
            recommendation=recommendation,
            recommended_algorithms=[],
            priority="N/A",
            family="Unknown",
            references=[GENERAL_PQC_REFERENCE],
        )

    # 4. Canonicalize use case
    canonical_use_case = normalize_use_case(raw_use_case_str, algorithm_hint=canonical_alg)
    if canonical_use_case is None:
        supported_use_cases = ", ".join(kb.get("use_cases", {}).keys())
        use_case_lower = raw_use_case_str.strip().lower()

        if use_case_lower in ("encryption", "public_key_encryption", "asymmetric_encryption"):
            reason = (
                f"The use case '{raw_use_case_str}' is ambiguous. Cryptographic operations must explicitly "
                f"distinguish between key establishment (key encapsulation/exchange) and symmetric bulk data encryption. "
                f"Supported canonical use cases: {supported_use_cases}."
            )
            recommendation = (
                "Please choose a supported use case: 'key_establishment' for key exchange/encapsulation, "
                "'digital_signatures' for authentication, or 'symmetric_encryption' for bulk data confidentiality."
            )
        else:
            reason = (
                f"Cryptographic use case '{raw_use_case_str}' is unrecognized. "
                f"Supported canonical use cases: {supported_use_cases}."
            )
            recommendation = "Choose one of the supported use cases: key_establishment, digital_signatures, symmetric_encryption."

        return _build_result(
            algorithm=canonical_alg,
            use_case=raw_use_case_str,
            risk_level="Unrecognized Use Case",
            reason=reason,
            recommendation=recommendation,
            recommended_algorithms=[],
            priority="N/A",
            family=kb.get("algorithms", {}).get(canonical_alg, {}).get("family", "Unknown"),
            references=[GENERAL_PQC_REFERENCE],
        )

    alg_data = kb.get("algorithms", {}).get(canonical_alg, {})
    supported_cases = alg_data.get("supported_use_cases", [])

    # 5. Check if algorithm supports the given use case
    if canonical_use_case not in supported_cases:
        return _handle_unsupported_combination(canonical_alg, canonical_use_case, alg_data)

    # 6. Retrieve assessment for valid combination
    assessments = alg_data.get("assessments", {})
    case_assessment = assessments.get(canonical_use_case)

    if not case_assessment:
        return _build_result(
            algorithm=canonical_alg,
            use_case=canonical_use_case,
            risk_level="Assessment Unavailable",
            reason=f"No detailed assessment defined for {canonical_alg} under use case '{canonical_use_case}'.",
            recommendation="Check the knowledge base configuration.",
            recommended_algorithms=[],
            priority="N/A",
            family=alg_data.get("family", "Unknown"),
            references=[GENERAL_PQC_REFERENCE],
        )

    return _build_result(
        algorithm=canonical_alg,
        use_case=canonical_use_case,
        risk_level=case_assessment.get("risk_level", "Unknown"),
        reason=case_assessment.get("reason", ""),
        recommendation=case_assessment.get("recommendation", ""),
        recommended_algorithms=case_assessment.get("recommended_algorithms", []),
        priority=case_assessment.get("priority", "N/A"),
        family=alg_data.get("family", "Unknown"),
        references=case_assessment.get("references", [GENERAL_PQC_REFERENCE]),
    )

